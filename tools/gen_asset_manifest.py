#!/usr/bin/env python3
"""Compile assets/art/manifest.json into C tables.

Same reasoning as the game data: generating C keeps a parser out of the
runtime and makes the asset set visible in a diff.

    python3 tools/gen_asset_manifest.py
"""
import argparse
import json
import os

HEADER = '''/* GENERATED by tools/gen_asset_manifest.py -- do not edit. */
#ifndef SONNY_ASSETS_GEN_H
#define SONNY_ASSETS_GEN_H

#include <stdint.h>

/* One named asset: a still has a single frame, an animation has several, in
   order. Paths are relative to the repository root. */
typedef struct {
    const char        *name;
    const char        *category;
    const char *const *frames;
    int32_t            frame_count;
} AssetEntry;

/* An animation state of the character model, as its frame labels define it.
   Frames are 1-based indices into the model's own frame list. */
typedef struct {
    const char *name;
    int32_t     start;
    int32_t     end;
    int32_t     length;
} AssetAnimation;

extern const AssetEntry SONNY_ASSETS[];
extern const int SONNY_ASSET_COUNT;
extern const AssetAnimation SONNY_ANIMATIONS[];
extern const int SONNY_ANIMATION_COUNT;

const AssetEntry *asset_find(const char *name);
const AssetAnimation *asset_animation(const char *name);

#endif
'''


def c_string(text):
    out = []
    for ch in str(text):
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ord(ch) < 32 or ord(ch) > 126:
            out.extend('\\%03o' % b for b in ch.encode('utf-8'))
        else:
            out.append(ch)
    return '"%s"' % ''.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-i', '--input', default='assets/art/manifest.json')
    ap.add_argument('-o', '--out', default='src/gen')
    args = ap.parse_args()

    with open(args.input, encoding='utf-8') as fh:
        manifest = json.load(fh)
    assets = manifest['assets']
    animations = manifest.get('animations') or {}

    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, 'assets_gen.h'), 'w',
              encoding='utf-8') as fh:
        fh.write(HEADER)

    lines = ['/* GENERATED by tools/gen_asset_manifest.py -- do not edit. */',
             '#include <string.h>', '#include "assets_gen.h"', '']

    for index, (name, entry) in enumerate(sorted(assets.items())):
        lines.append('static const char *const FRAMES_%d[] = { %s };'
                     % (index, ', '.join(c_string(f) for f in entry['frames'])))
    lines.append('')
    lines.append('const AssetEntry SONNY_ASSETS[] = {')
    for index, (name, entry) in enumerate(sorted(assets.items())):
        lines.append('    { %s, %s, FRAMES_%d, %d },'
                     % (c_string(name), c_string(entry['category']), index,
                        len(entry['frames'])))
    lines.append('};')
    lines.append('const int SONNY_ASSET_COUNT = '
                 '(int)(sizeof(SONNY_ASSETS) / sizeof(SONNY_ASSETS[0]));')
    lines.append('')
    lines.append('const AssetAnimation SONNY_ANIMATIONS[] = {')
    for name, a in sorted(animations.items(), key=lambda kv: kv[1]['start']):
        lines.append('    { %s, %d, %d, %d },'
                     % (c_string(name), a['start'], a['end'], a['length']))
    lines.append('};')
    lines.append('const int SONNY_ANIMATION_COUNT = '
                 '(int)(sizeof(SONNY_ANIMATIONS) / sizeof(SONNY_ANIMATIONS[0]));')
    lines.append('''
const AssetEntry *asset_find(const char *name)
{
    if (!name)
        return NULL;
    for (int i = 0; i < SONNY_ASSET_COUNT; i++)
        if (strcmp(SONNY_ASSETS[i].name, name) == 0)
            return &SONNY_ASSETS[i];
    return NULL;
}

const AssetAnimation *asset_animation(const char *name)
{
    if (!name)
        return NULL;
    for (int i = 0; i < SONNY_ANIMATION_COUNT; i++)
        if (strcmp(SONNY_ANIMATIONS[i].name, name) == 0)
            return &SONNY_ANIMATIONS[i];
    return NULL;
}''')

    with open(os.path.join(args.out, 'assets_gen.c'), 'w',
              encoding='utf-8') as fh:
        fh.write('\n'.join(lines) + '\n')

    print('%d assets, %d animations -> %s'
          % (len(assets), len(animations), args.out))


if __name__ == '__main__':
    main()
